const SIDO = "서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|전북|전남|경북|경남|제주";
// "충남도립대학교", "경기도청", "전남개발공사" 처럼 시·도 약칭 뒤에 공공기관 표시가 붙은 낱말
const SIDO_INSTITUTION = new RegExp(`^(${SIDO})(도립|시립|도청|시청|도교육청|시교육청|교육청|도의회|시의회|개발공사|도시공사|도시개발공사|관광공사|신용보증재단|경제진흥원|테크노파크|일자리재단|청년재단|문화재단|복지재단|의료원)`);

/** 낱말 하나가 가리키는 시·도 목록(모르면 빈 배열). "전남광주통합특별시"는 전남·광주 둘 다 */
export function regionsOfToken(token: string): string[] {
  const t = token.trim();
  if (!t) return [];
  // 공식 명칭으로 시작하는 낱말("제주특별자치도청", "전남광주통합특별시교육청")
  const official = OFFICIAL.find(([name]) => t.startsWith(name));
  if (official) return official[1];
  const inst = t.match(SIDO_INSTITUTION);
  if (inst) return [inst[1]];
  const sigungu = t.match(/^(.+?)(시|군)(청)?$/);
  if (sigungu && SIGUNGU.has(sigungu[1])) return [SIGUNGU.get(sigungu[1])!];
  return [];
}
